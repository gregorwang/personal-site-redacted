import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { dirname, join, extname, posix as pathPosix } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { imageAssets } from "./image-assets.config.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const rawDir = join(root, "assets", "images", "raw");
const outDir = join(root, "dist", "processed-images");
const manifestPath = join(root, "app", "generated", "image-manifest.ts");
const uploadManifestPath = join(root, "dist", "upload-manifest.json");

const CDN_BASE = "https://cdn.xn--cckl9nsb.com";
const OSS_BASE = "https://oss.xn--cckl9nsb.com";
const HASH_LEN = 8;
const WEBP_OPTIONS = { quality: 82, effort: 4 };
/** srcset 宽度档位：只生成比原图窄的档，原图本身作为最大一档 */
const VARIANT_WIDTHS = [320, 640, 1080, 1600];

mkdirSync(outDir, { recursive: true });

/** @type {Record<string, string>} */
const images = {};
/** @type {Record<string, string>} */
const r2KeyIndex = {};
/** 公开 URL → 可用宽度（升序，最后一项是原图宽度） */
/** @type {Record<string, number[]>} */
const imageWidths = {};
/** @type {Array<{ key: string, localFile: string, r2Key: string, base: string, contentType: string }>} */
const uploadQueue = [];

function findRawFile(asset) {
  const files = existsSync(rawDir) ? readdirSync(rawDir) : [];
  const match = files.find((name) => name.startsWith(`${asset.key}.`));
  if (match) return join(rawDir, match);
  return null;
}

for (const asset of imageAssets) {
  const rawPath = findRawFile(asset);
  if (!rawPath) {
    console.warn(`skip (no raw file): ${asset.key}`);
    continue;
  }

  const rawExt = extname(rawPath).toLowerCase();
  const isAnimated = asset.animated || rawExt === ".gif";
  const basename = asset.basename ?? asset.sourceKey.split("/").pop().replace(/\.[^.]+$/, "");
  const sourceDir = pathPosix.dirname(asset.sourceKey);
  const outSubdir = asset.base === "oss" ? join(outDir, "oss") : join(outDir, "cdn", sourceDir);
  mkdirSync(outSubdir, { recursive: true });

  let outputBuffer;
  let outputExt;
  let contentType;

  if (isAnimated) {
    outputBuffer = readFileSync(rawPath);
    outputExt = rawExt;
    contentType = rawExt === ".gif" ? "image/gif" : "application/octet-stream";
  } else {
    outputBuffer = await sharp(rawPath).webp(WEBP_OPTIONS).toBuffer();
    outputExt = ".webp";
    contentType = "image/webp";
  }

  const hash = createHash("sha256").update(outputBuffer).digest("hex").slice(0, HASH_LEN);
  const outputName = `${basename}.${hash}${outputExt}`;
  const localFile = join(outSubdir, outputName);
  writeFileSync(localFile, outputBuffer);

  const objectKey =
    sourceDir === "." ? outputName : `${sourceDir}/${outputName}`;
  const publicBase = asset.base === "oss" ? OSS_BASE : CDN_BASE;
  const publicUrl = `${publicBase}/${objectKey.split("/").map(encodeURIComponent).join("/")}`;

  images[asset.key] = publicUrl;
  r2KeyIndex[asset.sourceKey] = asset.key;

  uploadQueue.push({
    key: asset.key,
    localFile,
    r2Key: objectKey,
    base: asset.base,
    contentType,
  });

  console.log(`${asset.key} → ${outputName} (${(outputBuffer.length / 1024).toFixed(1)} KB)`);

  if (isAnimated) continue;

  // 缩小版沿用原图的 hash：内容由原图 + 宽度 + WEBP_OPTIONS 决定，原图或参数变了 hash 也会变
  const { width: originalWidth } = await sharp(outputBuffer).metadata();
  if (!originalWidth) continue;
  const widths = [];
  for (const width of VARIANT_WIDTHS.filter((w) => w < originalWidth)) {
    const variantBuffer = await sharp(rawPath).resize({ width }).webp(WEBP_OPTIONS).toBuffer();
    const variantName = `${basename}.${hash}.w${width}${outputExt}`;
    const variantFile = join(outSubdir, variantName);
    writeFileSync(variantFile, variantBuffer);
    uploadQueue.push({
      key: `${asset.key}@${width}`,
      localFile: variantFile,
      r2Key: sourceDir === "." ? variantName : `${sourceDir}/${variantName}`,
      base: asset.base,
      contentType,
    });
    widths.push(width);
    console.log(`  w${width} (${(variantBuffer.length / 1024).toFixed(1)} KB)`);
  }
  if (widths.length > 0) {
    imageWidths[publicUrl] = [...widths, originalWidth];
  }
}

const imageEntries = Object.entries(images)
  .map(([key, url]) => `  ${key}: ${JSON.stringify(url)},`)
  .join("\n");

const indexEntries = Object.entries(r2KeyIndex)
  .map(([sourceKey, manifestKey]) => `  ${JSON.stringify(sourceKey)}: ${JSON.stringify(manifestKey)},`)
  .join("\n");

const widthEntries = Object.entries(imageWidths)
  .map(([url, widths]) => `  ${JSON.stringify(url)}: [${widths.join(", ")}],`)
  .join("\n");

const manifestSource = `// AUTO-GENERATED by scripts/process-images.mjs — do not edit by hand.
export const IMAGE_CDN_BASE = ${JSON.stringify(CDN_BASE)};
export const IMAGE_OSS_BASE = ${JSON.stringify(OSS_BASE)};

export const images: Record<string, string> = {
${imageEntries}
};

export const r2KeyIndex: Record<string, string> = {
${indexEntries}
};

/** 原图 URL → srcset 可用宽度；缩小版文件名为 \`<name>.<hash>.w<width>.webp\` */
export const imageWidths: Record<string, number[]> = {
${widthEntries}
};

export type ImageManifestKey = string;
`;

writeFileSync(manifestPath, manifestSource);
writeFileSync(uploadManifestPath, JSON.stringify(uploadQueue, null, 2));

console.log(`\nWrote ${Object.keys(images).length} entries → ${manifestPath}`);
console.log(`Upload queue → ${uploadManifestPath}`);
